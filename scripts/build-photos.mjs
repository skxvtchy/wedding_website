#!/usr/bin/env node
/**
 * Rebuilds public/images/years from the local photo library in ./images/photos.
 *
 * - Converts HEIC/HEIF (via macOS `sips`) and every other format to JPEG
 * - Applies EXIF rotation, resizes to max 1800px, compresses with mozjpeg
 * - Sorts each year by capture date and writes lib/allPhotos.ts with dimensions
 *
 * Usage: node scripts/build-photos.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const libraryDir = fs
  .readdirSync(path.join(root, "images"))
  .map((d) => path.join(root, "images", d))
  .find((d) => path.basename(d).trim() === "photos");
const outRoot = path.join(root, "public/images/years");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "photos-"));
const MAX = 1800;
const EXT = /\.(heic|heif|jpe?g|png)$/i;

if (!libraryDir) throw new Error("images/photos not found");

function captureDate(file) {
  try {
    const out = execFileSync("mdls", ["-raw", "-name", "kMDItemContentCreationDate", file], {
      encoding: "utf8",
    });
    const t = Date.parse(out);
    if (!Number.isNaN(t)) return t;
  } catch {}
  return fs.statSync(file).mtimeMs;
}

async function convert(src, dest) {
  let input = src;
  if (/\.hei[cf]$/i.test(src)) {
    input = path.join(tmp, path.basename(src) + ".jpg");
    execFileSync("sips", ["-s", "format", "jpeg", "-s", "formatOptions", "95", src, "--out", input], {
      stdio: "ignore",
    });
  }
  const info = await sharp(input, { failOn: "none" })
    .rotate()
    .resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true, progressive: true })
    .toFile(dest);
  return { width: info.width, height: info.height };
}

fs.rmSync(outRoot, { recursive: true, force: true });
const entries = [];

for (const year of fs.readdirSync(libraryDir).filter((y) => /^\d{4}$/.test(y)).sort()) {
  const dir = path.join(libraryDir, year);
  const files = fs
    .readdirSync(dir)
    .filter((f) => EXT.test(f))
    .map((f) => path.join(dir, f))
    .map((f) => ({ f, t: captureDate(f) }))
    .sort((a, b) => a.t - b.t);

  fs.mkdirSync(path.join(outRoot, year), { recursive: true });
  let n = 0;
  for (const { f } of files) {
    const name = String(++n).padStart(3, "0") + ".jpg";
    try {
      const dims = await convert(f, path.join(outRoot, year, name));
      entries.push({ year, src: `/images/years/${year}/${name}`, ...dims });
      process.stdout.write(".");
    } catch (err) {
      n--;
      console.warn(`\nskipped ${f}: ${err.message}`);
    }
  }
  console.log(` ${year}: ${n}`);
}

const ts = `// Generated by scripts/build-photos.mjs — do not edit by hand.
export type PhotoItem = { year: string; src: string; width: number; height: number };

export const allPhotos: PhotoItem[] = ${JSON.stringify(entries, null, 2)};

export const photosByYear = allPhotos.reduce<Record<string, PhotoItem[]>>((acc, photo) => {
  (acc[photo.year] ??= []).push(photo);
  return acc;
}, {});

export const years = Object.keys(photosByYear).sort();
`;
fs.writeFileSync(path.join(root, "lib/allPhotos.ts"), ts);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`\n${entries.length} photos written.`);
